"""ストレージ層の共通インターフェース。

ローカル (PostgreSQL) と共有 (DynamoDB) の 2 実装があり、ルートはこのインターフェースだけを使う。
ID はどちらの実装でも「文字列として比較すると時系列順」になる (PostgreSQL は連番 int、DynamoDB は ULID)。
"""
from typing import Protocol


class ConflictError(Exception):
    """一意制約違反 (ユーザー名の重複など)"""


class NotFoundError(Exception):
    """対象が存在しない / 権限がない"""


class Storage(Protocol):
    name: str

    # ---- 稼働確認 ----
    def ping(self) -> dict: ...
    def info(self) -> dict: ...

    # ---- ユーザー ----
    def create_user(self, username: str, display_name: str, password_hash: str, avatar_color: str) -> dict: ...
    def get_user_with_hash(self, username: str) -> dict | None: ...
    def get_user(self, user_id) -> dict | None: ...
    def update_user(self, user_id, display_name: str | None, status_message: str | None) -> dict: ...
    def search_users(self, q: str, exclude_id) -> list[dict]: ...

    # ---- セッション ----
    def create_session(self, user_id) -> str: ...
    def delete_session(self, token: str) -> None: ...
    def user_from_token(self, token: str) -> dict | None: ...

    # ---- ルーム ----
    def list_rooms(self, me_id) -> list[dict]: ...
    def room_summary(self, room_id, me_id) -> dict | None: ...
    def is_member(self, room_id, user_id) -> bool: ...
    def room_member_ids(self, room_id) -> list: ...
    def create_room(self, room_type: str, name: str | None, member_ids: list, creator: dict) -> str: ...

    # ---- メッセージ ----
    def list_messages(self, room_id, before, after, limit: int) -> tuple[list[dict], bool]: ...
    def insert_message(self, room_id, sender: dict, mtype: str, content: str) -> dict: ...
    def get_message(self, room_id, message_id) -> dict | None: ...
    def mark_read(self, room_id, user_id, message_id): ...
    def unsend_message(self, room_id, message_id, user_id) -> dict | None: ...

    # ---- 初期データ ----
    def seed_demo(self) -> None: ...
